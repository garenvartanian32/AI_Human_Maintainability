template<uint_fast64_t Modulus> class modint{
    using u64=uint_fast64_t;
    public:
    u64 a;
    constexpr modint(const u64 x=0) noexcept:a(x%Modulus){}
    constexpr u64 &value() noexcept{return a;}
    constexpr const u64 &value() const noexcept{return a;}
    constexpr modint &operator+=(const modint &rhs) noexcept{
        a+=rhs.a;
        if (a>=Modulus) a-=Modulus;
        return *this;
    }
    constexpr modint operator+(const modint &rhs) const noexcept{
        return modint(*this)+=rhs;
    }
    constexpr modint &operator++() noexcept{
        return ++a,*this;
    }
    constexpr modint operator++(int) noexcept{
        modint t=*this; return ++a,t;
    }
    constexpr modint &operator-=(const modint &rhs) noexcept{
        if (a<rhs.a) a+=Modulus;
        a-=rhs.a;
        return *this;
    }
    constexpr modint operator-(const modint &rhs) const noexcept{
        return modint(*this)-=rhs;
    }
    constexpr modint &operator--() noexcept{
        return --a,*this;
    }
    constexpr modint operator--(int) noexcept{
        modint t=*this; return --a,t;
    }
    constexpr modint &operator*=(const modint &rhs) noexcept{
        a=a*rhs.a%Modulus;
        return *this;
    }
    constexpr modint operator*(const modint &rhs) const noexcept{
        return modint(*this)*=rhs;
    }
    constexpr modint &operator/=(modint rhs) noexcept{
        u64 exp=Modulus-2;
        while(exp){
            if (exp&1) *this*=rhs;
            rhs*=rhs; exp>>=1;
        }
        return *this;
    }
    constexpr modint operator/(const modint &rhs) const noexcept{
        return modint(*this)/=rhs;
    }
    constexpr modint operator-() const noexcept{
        return modint(Modulus-a);
    }
    constexpr bool operator==(const modint &rhs) const noexcept{
        return a==rhs.a;
    }
    constexpr bool operator!=(const modint &rhs) const noexcept{
        return a!=rhs.a;
    }
    constexpr bool operator!() const noexcept{return !a;}
    friend constexpr modint pow(modint rhs,long long exp) noexcept{
        modint res{1};
        while(exp){
            if (exp&1) res*=rhs;
            rhs*=rhs; exp>>=1;
        }
        return res;
    }
    template<class T> friend constexpr modint operator+(T x,modint y) noexcept{
        return modint(x)+y;
    }
    template<class T> friend constexpr modint operator-(T x,modint y) noexcept{
        return modint(x)-y;
    }
    template<class T> friend constexpr modint operator*(T x,modint y) noexcept{
        return modint(x)*y;
    }
    template<class T> friend constexpr modint operator/(T x,modint y) noexcept{
        return modint(x)/y;
    }
    friend ostream &operator<<(ostream &s,const modint &rhs) noexcept{
        return s << rhs.a;
    }
    friend istream &operator>>(istream &s,modint &rhs) noexcept{
        u64 a; rhs=modint{(s >> a,a)}; return s;
    }
};

using mint=modint<MOD>;

template<typename T> vector<T> divisor(T n){
    vector<T> res;
    for (T i=1;i*i<=n;++i) if (n%i==0){
        res.emplace_back(i);
        if (i!=n/i) res.emplace_back(n/i);
    }
    return res;
}

int main(){
    cin.tie(0);
    ios::sync_with_stdio(false);
    int S; cin >> S;
    mint ans=0;
    vector<int> div=divisor(S);
    sort(div.begin(),div.end());
    for (int d:div){
        if (d<9&&9*pow(10,d-1)<S/d) continue;
        ans+=9*pow((mint)10,d-1)-S/d+1;
    }
    vector<int> sum(8),upto(10);
    for (int i=1;i<8;++i) sum[i]=9*pow(10,i-1)*i;
    for (int i=1;i<10;++i) upto[i]=9*pow(10,i-1);
    auto calc=[](int k,int l,int dk,int dl,int uk,int ul,int up){
        int a=(uk-k)/dk,b=(l<=ul?0:(l-ul+dl-1)/dl),c=(l-1)/dl;
        return max(0,min({up-1,a,c})-b+1);
    };
    for (int i=1;i<7;++i){
        for (int j=i+2;j<9;++j){
            int rest=S;
            for (int k=i+1;k<j;++k) rest-=sum[k];
            if (rest<=0) continue;
            int g=gcd(i,j),k;
            if (rest%g!=0) continue;
            for (k=1;k<10;++k){
                if ((rest-i*k)%j==0) break;
            }
            if (rest-i*k<=0||(rest-i*k)%j!=0) continue;
            int l=(rest-i*k)/j,dk=j/g,dl=i/g;
            ans+=calc(k,l,dk,dl,upto[i],upto[j],INF);
        }
    }
    // debug(ans);
    int max_ok=S/9;
    ans+=max_ok-(upper_bound(div.begin(),div.end(),max_ok)-div.begin());
    for (int i=9;i>1;--i){
        int s=S/i+1,y=S%s,x=s-y;
        if (S%s==0) continue;
        // debug(i,s,x,y,calc(x,y,i-1,i,upto[i-1],upto[i],S/(i-1)-s+1));
        ans+=calc(x,y,i,i-1,upto[i-1],upto[i],S/(i-1)-s+1);
    }
    cout << ans << '\n';
}